// ── Training snapshot ──────────────────────────────────────────────────────

function describeWorkout(w: Workout, names: Record<string, Exercise>, units: Profile['units']): string {
  const parts = w.exercises.map((we) => {
    const sets = we.sets.filter((s) => s.kind === 'working' && (w.status !== 'done' || s.done));
    const name = names[we.exerciseId]?.name ?? we.exerciseId;
    const text = sets
      .map((s) => {
        const kg = w.status === 'done' ? (s.weightKg ?? 0) : s.targetWeightKg;
        const reps = w.status === 'done' ? s.reps : s.targetReps;
        const rir = w.status === 'done' && s.rir !== undefined ? ` RIR${s.rir}` : '';
        return `${kg > 0 ? formatWeight(kg, units, false) + '×' : ''}${reps}${rir}`;
      })
      .join(', ');
    return `${name}: ${text}`;
  });
  return parts.join('; ');
}

export async function trainingSnapshot(): Promise<string> {
  const profile = (await db.profile.get('me'))!;
  const [gyms, workouts, activities, exercises, planned] = await Promise.all([
    db.gyms.toArray(),
    db.workouts.where('status').equals('done').toArray(),
    db.activities.toArray(),
    allExercises(),
    db.workouts.where('status').anyOf('planned', 'active').toArray(),
  ]);
  const names = exerciseMap(exercises);
  const sets = flattenSets(workouts);
  const now = Date.now();
  const recovery = computeRecovery(sets, activities, names, now);
  const weekly = weeklySets(sets, names, now);
  const u = profile.units;
  const active = gyms.find((g) => g.id === profile.activeGymId);
  const score = strengthScore(sets, profile.bodyweightKg, profile.sex, now);

  const lines: string[] = [];
  lines.push(`Now: ${new Date(now).toLocaleString(undefined, { weekday: 'long', year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' })}`);
  lines.push(
    `Lifter: ${profile.name || 'unnamed'}; goal ${profile.goal}; ${profile.experience}; trains ${profile.daysPerWeek}×/week, ${profile.sessionMinutes} min sessions; bodyweight ${formatWeight(profile.bodyweightKg, u)}; units ${u}.`,
  );
  lines.push(`Active gym: ${active ? `${active.name} (${active.equipment.join(', ') || 'bodyweight only'})` : 'none'}. Other gyms: ${gyms.filter((g) => g !== active).map((g) => g.name).join(', ') || 'none'}.`);

  const tired = MUSCLE_IDS.filter((m) => recovery[m] < 0.95).sort((a, b) => recovery[a] - recovery[b]);
  lines.push(`Recovery: ${tired.length ? tired.map((m) => `${MUSCLES[m].name} ${Math.round(recovery[m] * 100)}%`).join(', ') + '; everything else fresh.' : 'all muscles fresh.'}`);

  const vol = MUSCLE_IDS.filter((m) => weeklySetTarget(m, profile.goal).max > 0).map((m) => {
    const t = weeklySetTarget(m, profile.goal);
    return `${MUSCLES[m].name} ${Math.round(weekly[m] * 10) / 10}/${t.min}–${t.max}`;
  });
  lines.push(`Hard sets in the last 7 days vs weekly target: ${vol.join(', ')}.`);

  if (score.lifts.length) {
    lines.push(
      `Strength score ${Math.round(score.overall)}/100 (${score.level}). Estimated 1RMs: ${score.lifts
        .map((l) => `${LIFT_NAMES[l.lift]} ${formatWeight(l.e1rmKg, u)} (${l.ratio.toFixed(2)}×BW, ${l.level})`)
        .join(', ')}.`,
    );
  }

  const recent = workouts.sort((a, b) => (b.finishedAt ?? 0) - (a.finishedAt ?? 0)).slice(0, 8);
  lines.push(`Total workouts logged: ${workouts.length}.`);
  if (recent.length) {
    lines.push('Recent workouts (newest first, working sets as weight×reps):');
    for (const w of recent) {
      lines.push(`- ${new Date(w.finishedAt ?? w.createdAt).toLocaleDateString(undefined, { weekday: 'short', month: 'short', day: 'numeric' })} "${w.name}": ${describeWorkout(w, names, u)}`);
    }
  }
  const recentActivities = activities.filter((a) => now - a.at < 14 * 86_400_000).sort((a, b) => b.at - a.at);
  if (recentActivities.length) {
    lines.push(
      `Other training, last 14 days: ${recentActivities
        .map((a) => `${new Date(a.at).toLocaleDateString(undefined, { weekday: 'short', month: 'short', day: 'numeric' })} ${a.kind} ${a.minutes} min ${a.intensity}`)
        .join('; ')}.`,
    );
  }
  for (const p of planned) {
    lines.push(`${p.status === 'active' ? 'Workout in progress' : "Today's planned workout"}: "${p.name}" — ${describeWorkout(p, names, u)}`);
  }
  return `<training_snapshot>\n${lines.join('\n')}\n</training_snapshot>`;
}

// ── Tools ──────────────────────────────────────────────────────────────────

const isStr = (v: unknown): v is string => typeof v === 'string';
const isInt = (v: unknown, min: number, max: number): v is number => Number.isInteger(v) && (v as number) >= min && (v as number) <= max;

async function runTool(name: string, input: unknown, onWorkout: (id: string) => void): Promise<{ text: string; error?: boolean }> {
  const i = (input ?? {}) as Record<string, unknown>;
  const profile = (await db.profile.get('me'))!;

  if (name === 'build_workout') {
    const avoid = Array.isArray(i.avoid_muscles) ? i.avoid_muscles : null;
    if (!FOCUS_VALUES.includes(i.focus as Focus) || !isInt(i.minutes, 15, 120) || !avoid || !avoid.every((m) => MUSCLE_IDS.includes(m as MuscleId))) {
      return { text: 'Invalid input: expected focus, minutes (15–120), avoid_muscles (muscle ids) and gym.', error: true };
    }
    const gyms = await db.gyms.toArray();
    const gym = isStr(i.gym) && i.gym.trim() ? gyms.find((g) => g.name.toLowerCase() === (i.gym as string).trim().toLowerCase()) : undefined;
    if (isStr(i.gym) && i.gym.trim() && !gym) {
      return { text: `No gym named "${i.gym}". Saved gyms: ${gyms.map((g) => g.name).join(', ')}.`, error: true };
    }
    const gen = generateWorkout(
      await loadGenerateInput({ focus: i.focus as Focus, minutes: i.minutes, avoidMuscles: avoid as MuscleId[], gymId: gym?.id, seed: Math.floor(Math.random() * 1e9) }),
    );
    const id = await savePlan(gen, gym?.id ?? profile.activeGymId);
    onWorkout(id);
    const names = exerciseMap(await allExercises());
    const list = gen.exercises
      .map((we) => {
        const w = we.sets.filter((s) => s.kind === 'working');
        const top = w[0];
        const load = top && top.targetWeightKg > 0 ? ` @ ${formatWeight(top.targetWeightKg, profile.units)}` : '';
        return `- ${names[we.exerciseId]?.name}: ${w.length}×${top?.targetReps}${load} — ${we.rationale}`;
      })
      .join('\n');
    return { text: `Saved "${gen.name}" (~${gen.estimatedMinutes} min, ${FOCUS_LABEL[gen.focusKind]}${gym ? `, at ${gym.name}` : ''}). Engine notes: ${gen.summary}\n${list}` };
  }

  if (name === 'get_exercise_history') {
    if (!isStr(i.exercise) || !i.exercise.trim()) return { text: 'Invalid input: exercise name required.', error: true };
    const library = await allExercises();
    const id = matchExercise(i.exercise, library);
    if (!id) return { text: `No exercise matching "${i.exercise}" in the library.`, error: true };
    const ex = library.find((e) => e.id === id)!;
    const all = flattenSets(await db.workouts.where('status').equals('done').toArray()).filter((s) => s.exerciseId === id);
    const sessions = groupSessions(all).slice(0, 10);
    if (!sessions.length) return { text: `${ex.name}: never logged.` };
    const lines = sessions.map((s) => {
      const sets = s.sets.map((x) => `${x.weightKg > 0 ? formatWeight(x.weightKg, profile.units, false) + '×' : ''}${x.reps}${x.rir !== undefined ? ` RIR${x.rir}` : ''}`).join(', ');
      const e1 = bestE1RM(s.sets);
      return `${new Date(s.at).toLocaleDateString(undefined, { month: 'short', day: 'numeric' })}: ${sets}${e1 > 0 ? ` (e1RM ${formatWeight(e1, profile.units)})` : ''}`;
    });
    return { text: `${ex.name}, newest first:\n${lines.join('\n')}` };
  }

  if (name === 'log_activity') {
    if (!ACTIVITY_KINDS.includes(i.kind as ActivityKind) || !isInt(i.minutes, 5, 600) || !INTENSITIES.includes(i.intensity as Intensity) || !isInt(i.days_ago, 0, 7)) {
      return { text: 'Invalid input: expected kind, minutes, intensity and days_ago.', error: true };
    }
    const at = new Date();
    at.setDate(at.getDate() - i.days_ago);
    if (i.days_ago > 0) at.setHours(18, 0, 0, 0);
    await db.activities.add({ id: uid(), kind: i.kind as ActivityKind, minutes: i.minutes, intensity: i.intensity as Intensity, at: at.getTime() });
    return { text: `Logged ${i.kind} ${i.minutes} min (${i.intensity}), ${i.days_ago === 0 ? 'today' : `${i.days_ago} day(s) ago`}.` };
  }

  return { text: `Unknown tool ${name}`, error: true };
}

// ── Conversation loop ──────────────────────────────────────────────────────

export interface TurnResult {
  text: string;
  workoutId?: string;
  /** Messages to append to the stored transcript (user turn, snapshot, replies, tool results). */
  appended: Anthropic.Beta.BetaMessageParam[];
}

export function friendlyError(err: unknown): string {
  if (err instanceof Anthropic.AuthenticationError) return 'Your API key was rejected. Check it in Settings → AI coach.';
  if (err instanceof Anthropic.PermissionDeniedError) return "This API key doesn't have access to that model.";
  if (err instanceof Anthropic.RateLimitError) return 'Rate limited by the API — wait a moment and try again.';
  if (err instanceof Anthropic.APIConnectionError) return "Couldn't reach the Claude API. Check your connection.";
  if (err instanceof Anthropic.APIError) return `Claude API error ${err.status ?? ''}: ${err.message}`;
  return err instanceof Error ? err.message : String(err);
}

/**
 * Runs one user turn: streams text through `onText`, executes tool calls
 * locally, and loops until the model finishes. The transcript is append-only:
 * prior turns are replayed exactly as the API returned them.
 */
export async function runTurn(opts: {
  apiKey: string;
  model: string;
  history: Anthropic.Beta.BetaMessageParam[];
  userText: string;
  onText: (fullText: string) => void;
  signal?: AbortSignal;
  /** Test hook. */
  fetch?: typeof fetch;
}): Promise<TurnResult> {
  // The key is the user's own and never leaves their device except to the API.
  const client = new Anthropic({ apiKey: opts.apiKey, dangerouslyAllowBrowser: true, fetch: opts.fetch });
  const appended: Anthropic.Beta.BetaMessageParam[] = [
    { role: 'user', content: opts.userText },
    { role: 'system', content: await trainingSnapshot() },
  ];
  let text = '';
  let workoutId: string | undefined;
  let jsonRetries = 0;
  // Server-side fallback is available for Opus and Sonnet on the Claude API.
  const fallback = opts.model.startsWith('claude-haiku') ? {} : { betas: ['server-side-fallback-2026-07-01'], fallbacks: 'default' as const };

  for (let round = 0; round < 8; round++) {
    const stream = client.beta.messages.stream(
      {
        model: opts.model,
        max_tokens: 16000,
        system: SYSTEM,
        tools: TOOLS,
        cache_control: { type: 'ephemeral' },
        output_config: { effort: 'medium' },
        messages: [...opts.history, ...appended],
        ...fallback,
      },
      { signal: opts.signal },
    );
    const prefix = text;
    let roundText = '';
    stream.on('text', (delta) => {
      roundText += delta;
      opts.onText(prefix + roundText);
    });

    let message: Anthropic.Beta.BetaMessage;
    try {
      message = await stream.finalMessage();
      jsonRetries = 0;
    } catch (err) {
      // Only an unparseable streamed tool input is retried; API errors surface.
      if (err instanceof Anthropic.APIError || opts.signal?.aborted || jsonRetries++ >= 2) throw err;
      continue;
    }
    text = prefix + roundText;

    if (message.stop_reason === 'refusal') {
      appended.push({ role: 'assistant', content: message.content });
      text += (text ? '\n\n' : '') + "I can't help with that one.";
      break;
    }
    appended.push({ role: 'assistant', content: message.content });
    if (message.stop_reason === 'pause_turn') continue;

    const toolUses = message.content.filter((b): b is Anthropic.Beta.BetaToolUseBlock => b.type === 'tool_use');
    if (toolUses.length === 0) break;
    if (message.stop_reason === 'max_tokens') {
      text += '\n\n(Response cut off.)';
      break;
    }

    const results: Anthropic.Beta.BetaToolResultBlockParam[] = [];
    for (const tu of toolUses) {
      try {
        const r = await runTool(tu.name, tu.input, (id) => (workoutId = id));
        results.push({ type: 'tool_result', tool_use_id: tu.id, content: r.text, is_error: r.error });
      } catch (err) {
        results.push({ type: 'tool_result', tool_use_id: tu.id, content: `Tool failed: ${friendlyError(err)}`, is_error: true });
      }
    }
    appended.push({ role: 'user', content: results });
    if (text && !text.endsWith('\n')) text += '\n\n';
  }

  return { text: text.trim(), workoutId, appended };
}
